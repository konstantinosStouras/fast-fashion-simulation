import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
import {SETTINGS,DEFAULT_CONFIG} from '../model.js';

test('assumption buttons acknowledge changes and persist the intended value',async t=>{
 const w=new JSDOM(readFileSync('index.html','utf8'),{url:'http://localhost:8791/?demo&studio=1'}).window;
 for(const key of ['document','location','localStorage','FormData'])globalThis[key]=w[key];
 globalThis.addEventListener=w.addEventListener.bind(w);
 const api=await import('../backend-demo.js');
 t.after(async()=>{await api.logout();await new Promise(r=>setTimeout(r,20));w.close();});
 await api.loginGoogle();
 await import('../main.js?assumption-feedback');
 for(let i=0;i<100 && !w.document.querySelector('.assumption-actions');i++)await new Promise(r=>setTimeout(r,10));
 const groups=w.document.querySelectorAll('.assumption-actions');
 assert.equal(groups.length,SETTINGS.length);
 for(const group of groups)assert.deepEqual([...group.querySelectorAll('button')].map(b=>b.dataset.op),['save','default','restore']);
 const form=w.document.querySelector('#create'), input=form.elements.demandMean;
 const group=input.closest('.settings-grid > div'), status=group.querySelector('[role=status]');
 const click=op=>group.querySelector('[data-op="'+op+'"]').click();
 const settle=()=>new Promise(r=>setTimeout(r,0));
 const storageKey='ffo:setup:'+api.currentUser().uid+':demandMean';
 input.value='500';click('save');await settle();
 assert.match(status.textContent,/500 saved for this setup/);
 assert.equal(w.sessionStorage.getItem(storageKey),'500');
 assert.equal((await api.getDefaults()).demandMean,DEFAULT_CONFIG.demandMean);
 input.value='510';input.dispatchEvent(new w.Event('input',{bubbles:true}));
 assert.equal(status.textContent,'');
 click('default');
 assert.equal(group.querySelector('[data-op=default]').textContent,'Saving…');
 await settle();
 assert.match(status.textContent,/510 saved as the default/);
 assert.equal((await api.getDefaults()).demandMean,510);
 assert.equal(w.sessionStorage.getItem(storageKey),null);
 click('restore');await settle();
 assert.equal(Number(input.value),DEFAULT_CONFIG.demandMean);
 assert.match(status.textContent,/restored to 480/);
 assert.equal((await api.getDefaults()).demandMean,510);
 input.value='-1';click('save');
 assert.equal(status.textContent,input.validationMessage);
 assert.equal(w.sessionStorage.getItem(storageKey),'480');
 const salvage=form.elements.salvage.closest('.settings-grid > div');
 form.elements.salvage.value='100';
 salvage.querySelector('[data-op=default]').click();await settle();
 assert.match(salvage.querySelector('[role=status]').textContent,/Could not save/);
 assert.equal((await api.getDefaults()).salvage,DEFAULT_CONFIG.salvage);
 assert.equal(salvage.querySelector('[data-op=default]').disabled,false);
});
