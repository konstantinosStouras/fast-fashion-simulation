import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
test('admin entrance supports Google/password/reset and denies student accounts',async t=>{
 const dom=new JSDOM(readFileSync('admin/index.html','utf8'),{url:'http://localhost:8791/admin/?demo'}),w=dom.window;
 for(const k of ['document','location','localStorage','sessionStorage','FormData'])globalThis[k]=w[k];globalThis.addEventListener=w.addEventListener.bind(w);
 const $=s=>w.document.querySelector(s),click=s=>$(s).click(),submit=()=>$('#admin-login').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
 const wait=async fn=>{for(let i=0;i<100;i++){await new Promise(r=>setTimeout(r,10));if(fn())return;}throw Error('Expected admin login state did not appear');};
 const api=await import('../backend-demo.js');t.after(async()=>{await api.logout();await new Promise(r=>setTimeout(r,20));w.close();});
 assert.equal($('#admin-login'),null,'the initial document must not paint a login form');
 await import('../main.js?admin-login-test');await wait(()=>$('#admin-login'));
 assert.equal($('#admin-email').value,'admin@admin.com');assert.equal($('#admin-password').autocomplete,'current-password');
 click('#admin-reset');await wait(()=>$('#admin-message').textContent.includes('password link'));
 click('#admin-google');await wait(()=>$('#create'));const adminUid=api.currentUser().uid;
 assert.equal(location.pathname,'/admin/');assert.equal($('#admin-login'),null);
 click('#out');await wait(()=>$('#admin-login'));
 $('#admin-password').value='synthetic-only';submit();await wait(()=>$('#create'));
 assert.notEqual(api.currentUser().uid,adminUid);assert.equal(await api.role(),'instructor');
 click('#out');await wait(()=>$('#admin-login'));
 $('#admin-email').value='student@example.test';$('#admin-password').value='synthetic-only';submit();await wait(()=>$('#admin-message')?.textContent.includes('does not have administrator access'));
 assert.equal($('#create'),null);assert.equal($('#admin-login').hidden,true);
 click('#admin-switch');await wait(()=>$('#admin-login')&&!$('#admin-login').hidden);
 await api.register('unverified@example.test','synthetic-only',{firstName:'Test',lastName:'Student',universityId:'1'});
 await wait(()=>$('#admin-message')?.textContent.includes('Verify your email'));assert.equal($('#admin-verify').hidden,false);assert.equal($('#create'),null);
});
